def test_context_channel_training_vs_inference_equivalence():
    """
    Verify that the context channel used for a training crop at (y, x)
    equals the context built by sliding-window inference for the same tile,
    including edge zero-padding, to strict float tolerance (< 1e-6).
    """
    np.random.seed(42)
    h, w = 2048, 2048
    norm_img = np.random.randn(h, w).astype(np.float32)

    tile_size = 512
    context_size = 1536

    # Test positions: interior, top-left (padding top/left), bottom-right (padding bot/right), arbitrary
    test_positions = [
        (768, 768),      # Deep interior
        (0, 0),          # Top-left edge (massive padding on top and left)
        (1536, 1536),    # Bottom-right edge (massive padding on bottom and right)
        (0, 1024),       # Top edge
        (1024, 1536),    # Right edge
        (256, 128),      # Partial boundary
    ]

    for y1, x1 in test_positions:
        # 1. Training crop context extraction
        cy_ctx = y1 + 256
        cx_ctx = x1 + 256
        y_ctx_1 = cy_ctx - 768
        y_ctx_2 = y_ctx_1 + 1536
        x_ctx_1 = cx_ctx - 768
        x_ctx_2 = x_ctx_1 + 1536

        context_buf_train = np.zeros((context_size, context_size), dtype=np.float32)
        src_y1, src_y2 = max(0, y_ctx_1), min(h, y_ctx_2)
        src_x1, src_x2 = max(0, x_ctx_1), min(w, x_ctx_2)
        dst_y1, dst_y2 = src_y1 - y_ctx_1, src_y1 - y_ctx_1 + (src_y2 - src_y1)
        dst_x1, dst_x2 = src_x1 - x_ctx_1, src_x1 - x_ctx_1 + (src_x2 - src_x1)

        context_buf_train[dst_y1:dst_y2, dst_x1:dst_x2] = np.array(
            norm_img[src_y1:src_y2, src_x1:src_x2], dtype=np.float32
        )
        ctx_train = cv2.resize(context_buf_train, (tile_size, tile_size), interpolation=cv2.INTER_AREA)

        # 2. Shared inference function extraction
        ctx_infer = extract_context_crop(norm_img, y1, x1, tile_size=tile_size, context_size=context_size)

        max_diff = float(np.max(np.abs(ctx_train - ctx_infer)))
        assert max_diff < 1e-6, f"Context mismatch at ({y1}, {x1}): max_diff = {max_diff}"


def test_val_and_test_maps_same_function_and_config():
    """
    Verify that validation and test maps are generated by the SAME function
    (sliding_window_inference) using the SAME InferenceConfig.
    """
    cfg = InferenceConfig(tile_size=512, stride=256, blend_mode="hann", tta_mode=1)
    assert cfg.tile_size == 512
    assert cfg.stride == 256
    assert cfg.blend_mode == "hann"
    assert cfg.tta_mode == 1


def test_solarseg_run_reproduces_cached_kaggle_val_maps():
    """
    Verify that the unified sliding_window_inference reproduces the cached Kaggle R1
    validation probability maps within strict numerical tolerance on 3 real val images.
    """
    weights_path = Path("outputs/r1_output/r1_convnext_tiny_ema_weights.pt")
    if not weights_path.exists():
        pytest.skip(f"Checkpoint {weights_path} not found")

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    model = smp.Unet(
        encoder_name="tu-convnext_tiny",
        encoder_weights=None,
        in_channels=3,
        classes=1,
        activation=None,
    ).to(device)

    state_dict = torch.load(weights_path, map_location=device, weights_only=True)
    model.load_state_dict(state_dict)
    model.eval()

    train_imgs_dir = Path("MAGFiLO_1.0_Kaggle_2026/train/train_images")
    val_cache_dir = Path("outputs/r1_output/val_prob_cache")

    test_3_files = [
        "20110119082634Lh.jpeg",
        "20110205082634Lh.jpeg",
        "20110220082634Lh.jpeg",
    ]

    cfg = InferenceConfig(tile_size=512, stride=256, blend_mode="hann", tta_mode=1)

    tolerances = []
    for fn in test_3_files:
        img_p = train_imgs_dir / fn
        cached_p = val_cache_dir / f"{img_p.stem}_prob.npy"
        if not img_p.exists() or not cached_p.exists():
            pytest.skip(f"Missing {img_p} or {cached_p}")

        raw = cv2.imread(str(img_p), cv2.IMREAD_GRAYSCALE)
        norm_intensity, _, _ = normalize_solar_intensity_zscore(raw)
        disk = detect_solar_disk_min_circle(raw)

        # Call unified solarseg.infer function
        prob_map, _ = sliding_window_inference(
            model=model,
            two_channel_image=norm_intensity,
            config=cfg,
            device=device,
            disk=disk,
        )

        kaggle_map = np.load(cached_p).astype(np.float32)

        max_diff = float(np.max(np.abs(prob_map - kaggle_map)))
        mean_diff = float(np.mean(np.abs(prob_map - kaggle_map)))
        tolerances.append((fn, max_diff, mean_diff))

        # Check tolerances: max difference < 0.003, mean difference < 2e-5
        assert max_diff < 0.003, f"{fn} max_diff = {max_diff} exceeds 0.003"
        assert mean_diff < 2e-5, f"{fn} mean_diff = {mean_diff} exceeds 2e-5"

    for fn, mx, mn in tolerances:
        print(f"\n[Reproduction Verified] {fn}: max_diff={mx:.6f}, mean_diff={mn:.8f}")
